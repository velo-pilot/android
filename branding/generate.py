#!/usr/bin/env python3
"""Generates the VeloPilot launcher icon, splash logo, F-Droid icon and UI font.

The images come from velopilot.svg, the launcher and F-Droid icon of the dev builds (flavour velopilotDev,
res-velopilot-dev) from velopilot-dev.svg, and the font resources from the variable font in fonts/ (Xmind, SIL OFL
1.1, see fonts/OFL.txt): Android before 8 cannot pick a weight from a variable font, so the app gets static
instances of the weights it uses. Needs Inkscape, ImageMagick, fontTools and the Xmind font installed (for
the "P" and the "VeloPilot" text, which become paths). Run it again after changing an SVG:

    branding/generate.py
"""
import re
import subprocess
import sys
import tempfile
import xml.etree.ElementTree as ET
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / "branding" / "velopilot.svg"
DEV_SOURCE = ROOT / "branding" / "velopilot-dev.svg"
RES = ROOT / "OsmAnd" / "res-velopilot"
DEV_RES = ROOT / "OsmAnd" / "res-velopilot-dev"
FDROID_ICON = ROOT / "build-container" / "fdroid" / "icon.png"
FDROID_DEV_ICON = ROOT / "build-container" / "fdroid" / "icon-dev.png"
VARIABLE_FONT = ROOT / "branding" / "fonts" / "Xmind_VariableFont_wght.ttf"
FONT_WEIGHTS = {400: "regular", 500: "medium", 700: "bold"}

SVG = "{http://www.w3.org/2000/svg}"
DENSITIES = {"mdpi": 1, "hdpi": 1.5, "xhdpi": 2, "xxhdpi": 3, "xxxhdpi": 4}

# Adaptive icons are 108dp; launchers show the middle 72dp and keep the middle 66dp circle unmasked.
# The 512 px artwork gets this size, so that the "P" in its corner stays inside a round mask.
ADAPTIVE_ART_DP = 60
SPLASH_CANVAS_DP = 240
SPLASH_LOGO_DP = 192
TEXT_HEIGHT_DP = 36
TEXT_DRAWABLES = ["image_text_osmand_plus", "image_text_osmand_plus_pro", "image_text_osmand_plus_osmlive"]


def run(*args):
	subprocess.run(args, check=True, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)


def text_to_path(src, dst):
	run("inkscape", str(src), "--export-text-to-path", "--export-plain-svg", f"--export-filename={dst}")


def parse_transform(value):
	"""Returns (scale, tx, ty) of a translate() or uniform matrix() transform."""
	if not value:
		return 1.0, 0.0, 0.0
	numbers = [float(n) for n in re.findall(r"-?[\d.]+(?:e-?\d+)?", value)]
	if value.startswith("translate"):
		return 1.0, numbers[0], numbers[1] if len(numbers) > 1 else 0.0
	if value.startswith("matrix") and numbers[1] == 0 and numbers[2] == 0 and numbers[0] == numbers[3]:
		return numbers[0], numbers[4], numbers[5]
	sys.exit(f"Unsupported transform: {value}")


def fill_of(element, inherited):
	"""Returns the fill of element as #RRGGBB, or as #AARRGGBB when it is translucent."""
	style = dict(item.split(":", 1) for item in element.get("style", "").split(";") if ":" in item)
	color = element.get("fill") or style.get("fill") or "#" + inherited[-6:]
	alpha = inherited[1:3] if len(inherited) == 9 else ""
	opacity = element.get("fill-opacity") or style.get("fill-opacity")
	if opacity is not None:
		alpha = f"{round(float(opacity) * 255):02X}" if float(opacity) < 1 else ""
	return f"#{alpha}{color[1:]}".upper()


def collect_paths(element, fill="#000000"):
	"""Returns the paths below element as (scale, tx, ty, fill, d), with the transforms of their groups."""
	paths = []
	fill = fill_of(element, fill)
	scale, tx, ty = parse_transform(element.get("transform"))
	for child in element:
		if child.tag == SVG + "path":
			s, x, y = parse_transform(child.get("transform"))
			paths.append((s, x, y, fill_of(child, fill), child.get("d")))
		elif child.tag == SVG + "g":
			paths.extend(collect_paths(child, fill))
	if (scale, tx, ty) != (1.0, 0.0, 0.0):
		paths = [(scale, tx, ty, None, paths)]
	return paths


def vector_groups(paths, indent):
	lines = []
	for scale, tx, ty, fill, d in paths:
		pad = " " * indent
		if fill is None:  # a group
			lines.append(f'{pad}<group android:scaleX="{scale}" android:scaleY="{scale}"'
			             f' android:translateX="{tx}" android:translateY="{ty}">')
			lines.extend(vector_groups(d, indent + 4))
			lines.append(f"{pad}</group>")
			continue
		if (scale, tx, ty) != (1.0, 0.0, 0.0):
			lines.append(f'{pad}<group android:scaleX="{scale}" android:scaleY="{scale}"'
			             f' android:translateX="{tx}" android:translateY="{ty}">')
			pad += "    "
		d = " ".join(d.split())
		lines.append(f'{pad}<path\n{pad}    android:fillColor="{fill}"\n{pad}    android:pathData="{d}" />')
		if (scale, tx, ty) != (1.0, 0.0, 0.0):
			lines.append(f"{pad[:-4]}</group>")
	return lines


def vector(width, height, viewport_width, viewport_height, body, comment, source=SOURCE):
	return "\n".join([
		'<?xml version="1.0" encoding="utf-8"?>',
		f"<!-- {comment} Generated by branding/generate.py from branding/{source.name}. -->",
		'<vector xmlns:android="http://schemas.android.com/apk/res/android"',
		f'    android:width="{width}dp"',
		f'    android:height="{height}dp"',
		f'    android:viewportWidth="{viewport_width}"',
		f'    android:viewportHeight="{viewport_height}">',
		*body,
		"</vector>",
		"",
	])


def write(path, text):
	path.parent.mkdir(parents=True, exist_ok=True)
	path.write_text(text)


def launcher_icon(plain, source, res, name):
	"""Writes the adaptive launcher icon @mipmap/icon_<name> of plain (source after text_to_path) to res."""
	root = ET.parse(plain).getroot()
	size = float(root.get("viewBox").split()[2])
	layer = root.find(f"{SVG}g")
	background = layer.find(f"{SVG}rect")
	background_color = fill_of(background, "#000000")
	art = collect_paths_without(layer, background)

	scale = ADAPTIVE_ART_DP / size
	offset = (108 - ADAPTIVE_ART_DP) / 2
	foreground = [f'    <group android:scaleX="{scale:.6f}" android:scaleY="{scale:.6f}"'
	              f' android:translateX="{offset}" android:translateY="{offset}">',
	              *vector_groups(art, 8),
	              "    </group>"]
	write(res / "drawable" / f"ic_launcher_{name}_foreground.xml",
	      vector(108, 108, 108, 108, foreground, "Adaptive icon foreground and monochrome layer.", source))
	write(res / "drawable" / f"ic_launcher_{name}_background.xml",
	      vector(108, 108, 108, 108,
	             [f'    <path\n        android:fillColor="{background_color}"\n        android:pathData="M0,0h108v108h-108z" />'],
	             "Adaptive icon background.", source))
	write(res / "mipmap-anydpi-v26" / f"icon_{name}.xml", "\n".join([
		'<?xml version="1.0" encoding="utf-8"?>',
		'<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">',
		f'    <background android:drawable="@drawable/ic_launcher_{name}_background" />',
		f'    <foreground android:drawable="@drawable/ic_launcher_{name}_foreground" />',
		f'    <monochrome android:drawable="@drawable/ic_launcher_{name}_foreground" />',
		"</adaptive-icon>",
		"",
	]))


def collect_paths_without(layer, skip):
	paths = []
	for child in layer:
		if child is skip:
			continue
		wrapper = ET.Element(SVG + "g")
		wrapper.append(child)
		paths.extend(collect_paths(wrapper))
	return paths


def png(src, dst, width, height=None):
	dst.parent.mkdir(parents=True, exist_ok=True)
	run("inkscape", str(src), "--export-type=png", f"--export-filename={dst}", "-w", str(width),
	    "-h", str(height or width))
	run("magick", str(dst), "-strip", str(dst))


def bitmaps(plain, dev_plain, tmp):
	for density, factor in DENSITIES.items():
		png(plain, RES / f"mipmap-{density}" / "icon_velopilot.png", round(48 * factor))
		png(dev_plain, DEV_RES / f"mipmap-{density}" / "icon_velopilot_dev.png", round(48 * factor))
	png(plain, FDROID_ICON, 512)
	png(dev_plain, FDROID_DEV_ICON, 512)

	# Splash logo: the icon with rounded corners, centred on a transparent canvas
	for density, factor in DENSITIES.items():
		logo = round(SPLASH_LOGO_DP * factor)
		canvas = round(SPLASH_CANVAS_DP * factor)
		square = tmp / f"logo-{density}.png"
		png(plain, square, logo)
		radius = round(logo * 0.18)
		dst = RES / f"drawable-{density}" / "ic_logo_splash_osmand_plus.png"
		dst.parent.mkdir(parents=True, exist_ok=True)
		run("magick", str(square),
		    "(", "-size", f"{logo}x{logo}", "xc:none", "-fill", "white",
		    "-draw", f"roundrectangle 0,0,{logo - 1},{logo - 1},{radius},{radius}", ")",
		    "-compose", "DstIn", "-composite", "-compose", "Over",
		    "-background", "none", "-gravity", "center", "-extent", f"{canvas}x{canvas}",
		    "-strip", str(dst))


def splash_text(tmp):
	"""The app name under the splash logo, in the font of the "P"; the app tints it."""
	text_svg = tmp / "text.svg"
	text_svg.write_text(
		'<svg xmlns="http://www.w3.org/2000/svg" width="1000" height="200" viewBox="0 0 1000 200">'
		'<text x="0" y="100" style="font-family:Xmind;font-weight:bold;font-size:100px;fill:#ffffff">'
		"VeloPilot</text></svg>")
	plain = tmp / "text-plain.svg"
	text_to_path(text_svg, plain)
	bbox = subprocess.run(["inkscape", "--query-all", str(plain)], check=True, capture_output=True,
	                      text=True).stdout.splitlines()[0].split(",")
	# --query-all reports px of the 1000x200 viewBox, which match the user units
	x, y, w, h = (float(v) for v in bbox[1:])
	root = ET.parse(plain).getroot()
	paths = collect_paths(root, "#FFFFFF")
	scale = TEXT_HEIGHT_DP / h
	width = round(w * scale, 2)
	body = [f'    <group android:scaleX="{scale:.6f}" android:scaleY="{scale:.6f}"'
	        f' android:translateX="{-x * scale:.4f}" android:translateY="{-y * scale:.4f}">',
	        *vector_groups(paths, 8),
	        "    </group>"]
	for name in TEXT_DRAWABLES:
		write(RES / "drawable" / f"{name}.xml",
		      vector(width, TEXT_HEIGHT_DP, width, TEXT_HEIGHT_DP, body, "Splash screen app name."))


def fonts():
	from fontTools.ttLib import TTFont
	from fontTools.varLib import instancer

	fonts_dir = RES / "font"
	fonts_dir.mkdir(parents=True, exist_ok=True)
	entries = []
	for weight, name in FONT_WEIGHTS.items():
		font = instancer.instantiateVariableFont(TTFont(VARIABLE_FONT), {"wght": weight})
		font["OS/2"].usWeightClass = weight
		font.save(fonts_dir / f"xmind_{name}.ttf")
		entries.append(f'''    <font
        android:font="@font/xmind_{name}"
        android:fontStyle="normal"
        android:fontWeight="{weight}"
        app:font="@font/xmind_{name}"
        app:fontStyle="normal"
        app:fontWeight="{weight}" />''')
	write(fonts_dir / "app_font.xml", "\n".join([
		'<?xml version="1.0" encoding="utf-8"?>',
		"<!-- UI font: Xmind (SIL OFL 1.1, branding/fonts/OFL.txt). Generated by branding/generate.py. -->",
		'<font-family xmlns:android="http://schemas.android.com/apk/res/android"',
		'    xmlns:app="http://schemas.android.com/apk/res-auto">',
		*entries,
		"</font-family>",
		"",
	]))


def main():
	with tempfile.TemporaryDirectory() as tmp:
		tmp = Path(tmp)
		plain = tmp / "velopilot-plain.svg"
		text_to_path(SOURCE, plain)
		dev_plain = tmp / "velopilot-dev-plain.svg"
		text_to_path(DEV_SOURCE, dev_plain)
		launcher_icon(plain, SOURCE, RES, "velopilot")
		launcher_icon(dev_plain, DEV_SOURCE, DEV_RES, "velopilot_dev")
		bitmaps(plain, dev_plain, tmp)
		splash_text(tmp)
	fonts()


if __name__ == "__main__":
	main()
